def validate(kb: dict) -> None:
    ids, problems = set(), []
    for cat in ("yoga", "exercise", "diet", "lifestyle", "home_care"):
        for item in kb[cat]:
            if item["id"] in ids:
                problems.append(f"duplicate id {item['id']}")
            ids.add(item["id"])
            for c in item.get("conditions", []):
                if c not in PATIENT_TAGS:
                    problems.append(f"{item['id']}: unknown condition tag {c}")
            for a in item.get("avoid_if", []):
                if a not in AVOID_TAGS:
                    problems.append(f"{item['id']}: unknown avoid tag {a}")
            if "evidence" in item and item["evidence"] not in EVIDENCE:
                problems.append(f"{item['id']}: bad evidence value")
            if "pregnancy" in item and item["pregnancy"] not in PREGNANCY:
                problems.append(f"{item['id']}: bad pregnancy value")
    for item in kb["yoga"] + kb["exercise"]:
        if not item["steps"]:
            problems.append(f"{item['id']}: no steps")
        if item["level"] not in LEVELS:
            problems.append(f"{item['id']}: bad level")
    if problems:
        raise SystemExit("Dataset validation failed:\n" + "\n".join(problems))


